/**
 * page-shell.mjs — the frame shared by the site's generated pages (the
 * exercise library, What's new): head, header and footer, with the mark,
 * the page-reveal script and the footer copied from index.html so they
 * never drift from the homepage.
 */
import fs from "node:fs";
import path from "node:path";

const INDEX = path.join(path.resolve(path.dirname(new URL(import.meta.url).pathname), ".."), "public", "index.html");

export const esc = (t) => String(t).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

/** The site's other pages, in header order: [href, label]. */
const PAGES = [["exercises.html", "Exercises"], ["whats-new.html", "What's new"]];

export function shell({ generator, title, description, active, body, script = "js/site/library.js" }) {
  const index = fs.readFileSync(INDEX, "utf8");
  const cut = (from, to) => { const i = index.indexOf(from); const j = index.indexOf(to, i); if (i < 0 || j < 0) throw new Error(`index.html is missing ${from}`); return index.slice(i, j); };
  const reveal = cut("<script>addEventListener(\"pagereveal\"", "\n") + "\n";
  const symbols = cut("<!-- Shared SVG symbol for the VertexForm mark", "<header");
  const footer = cut("<footer class=\"foot\"", "<div class=\"file-warn\"");
  const links = PAGES.map(([href, label]) => `<a href="${href}"${href === active ? ' class="active" aria-current="page"' : ""}>${esc(label)}</a>`).join("\n      ");
  return `<!DOCTYPE html>
<!-- Generated by ${generator}. Don't edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}" />
<meta name="theme-color" content="#090d1c" />
<link rel="preload" href="fonts/unbounded-latin-500-normal.woff2" as="font" type="font/woff2" crossorigin />
<link rel="preload" href="fonts/instrument-sans-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin />
<link rel="stylesheet" href="css/fonts.css" />
<link rel="stylesheet" href="css/site.css" />
<link rel="stylesheet" href="css/transitions.css" />
${reveal}<link rel="icon" href="favicon.svg" type="image/svg+xml" />
<link rel="manifest" href="manifest.webmanifest" />
<script>document.documentElement.classList.add("js");</script>
</head>
<body data-tone="dark" class="no-rail">

<a class="skip" href="#main">Skip to content</a>

${symbols}<header class="nav">
  <div class="wrap nav-row">
    <a class="logo" href="index.html" aria-label="VertexForm home">
      <svg class="logo-mark" aria-hidden="true"><use href="#mark"/></svg>
      <span>Vertex<em>Form</em></span>
    </a>
    <nav aria-label="Primary">
      <a href="index.html#how">How it works</a>
      ${links}
    </nav>
    <a class="btn btn-grad btn-sm" href="app.html">Start training</a>
  </div>
</header>

<main id="main">
${body}
</main>

${footer}<script type="module" src="${script}"></script>
</body>
</html>
`;
}
